#' Linked Dataset (n = 1000) for a Simple Illustration
#'
#' The \code{LD1000} data set contains a simulated cohort of 1,000 individuals
#' designed to replicate a secondary analysis scenario where records from
#' disparate data sources must be linked prior to performing regression analyses.
#'
#' To establish this cohort, demographic covariates were generated in one file
#' and a binary clinical outcome was generated in a separate file. The two files
#' were linked probabilistically using the Fellegi-Sunter model without unique identifiers,
#' and 1:1 matching was enforced via a linear sum assignment problem (LSAP). This
#' record linkage results in a mismatch rate of approximately 20%.
#'
#' \code{LD1000} provides variables of primary interest for secondary analysis
#' alongside examples of linkage paradata.
#'
#' \itemize{
#'   \item \code{Disease_Status}: Binary clinical outcome variable (0 or 1).
#'   \item \code{BMI}: Body Mass Index of the individual.
#'   \item \code{Age}: Age of the individual.
#'   \item \code{Treatment}: Binary indicator of treatment assignment (0 or 1).
#'   \item \code{fl_prob}: The posterior match probability assigned to the linked
#'   record pair by the probabilistic linkage algorithm (\code{fastLink}).
#'   \item \code{safe_match}: A logical indicator (\code{TRUE} / \code{FALSE}) denoting
#'   whether the linked record pair had perfect string agreement on both first
#'   and last names and exact agreement on birth year.
#'   \item \code{bm}: Birth month (1-12) used as a blocking variable during the
#'   probabilistic record linkage process and treated as blocks for the clerical
#'   audit.
#'   \item \code{block_mrate}: Estimated block-level mismatch rate. This variable
#'   was generated by simulating a clerical review (audit) of 20 randomly sampled
#'   records per birth-month block. Rates were adjusted as in Chambers (2009) to
#'   prevent values of exactly 1 or 0.
#'   \item \code{True_Disease_Status}: The unobservable true clinical outcome variable (0 or 1) that corresponds to the individual's actual record.
#'   \item \code{is_match}: The latent true match status (\code{TRUE} = correct match,
#'   \code{FALSE} = mismatch). Note: This variable is provided for benchmarking
#'   and is unobserved in real-world secondary analysis settings.
#' }
#'
#' @docType data
#' @name LD1000
#' @usage data(LD1000)
#' @format A data frame with 1,000 rows and 10 variables.
#'
#' @references
#' Chambers, R. (2009). Regression analysis of probability-linked data.
#' \emph{Official Statistics Research Series}, 4, 1-15.
#'
#' Sariyar, M., & Borg, A. (2026). RecordLinkage: Record Linkage Functions
#' for Linking and Deduplicating Data Sets. R package version 0.4-12.6.
#'
#' Enamorado, T., Fifield, B., & Imai, K. (2023). fastLink: Fast Probabilistic Record
#' Linkage with Missing Data. R package version 0.6.1.
#'
#' @keywords datasets
"LD1000"
